// Map lat/lon coordinates to approximate Indian states for auto-detection
// (Delhi, Maharashtra, Karnataka, Tamil Nadu, Uttar Pradesh, West Bengal)
export const detectStateFromCoordinates = (lat, lon) => {
  // Simple bounding box checks or distance to capitals for simulation
  if (lat > 28.0 && lat < 29.0 && lon > 76.5 && lon < 78.0) {
    return "Delhi";
  }
  if (lat > 18.0 && lat < 21.0 && lon > 72.0 && lon < 75.0) {
    return "Maharashtra"; // Mumbai area
  }
  if (lat > 12.0 && lat < 14.5 && lon > 76.5 && lon < 78.5) {
    return "Karnataka"; // Bangalore area
  }
  if (lat > 12.5 && lat < 13.5 && lon > 79.5 && lon < 80.5) {
    return "Tamil Nadu"; // Chennai area
  }
  if (lat > 25.0 && lat < 28.0 && lon > 80.0 && lon < 84.0) {
    return "Uttar Pradesh"; // Lucknow area
  }
  if (lat > 22.0 && lat < 23.5 && lon > 87.5 && lon < 89.0) {
    return "West Bengal"; // Kolkata area
  }
  
  // Default fallback
  return "Delhi";
};
